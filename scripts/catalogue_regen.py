"""Regenerate catalogue/RESULTS.md from catalogue/results.yaml."""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ALLOWED = frozenset({"pass", "rest-defect", "api-gap", "java-bound"})
ROOT = Path(__file__).resolve().parents[1]
YAML_PATH = ROOT / "catalogue" / "results.yaml"
MD_PATH = ROOT / "catalogue" / "RESULTS.md"


def main() -> int:
    data = yaml.safe_load(YAML_PATH.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or "entries" not in data:
        print(f"ERROR: {YAML_PATH} must contain an 'entries' list", file=sys.stderr)
        return 1

    entries = data["entries"] or []
    lines = [
        "# pki-cli result catalogue",
        "",
        "Generated from `catalogue/results.yaml`. Do not edit this file by hand;",
        "change the YAML and run `python scripts/catalogue_regen.py`.",
        "",
        "| id | command | status | notes | classification_todo |",
        "| --- | --- | --- | --- | --- |",
    ]

    for entry in entries:
        status = entry.get("status")
        todo = bool(entry.get("classification_todo", False))
        # null status is allowed only while awaiting human classification
        if status is None:
            if not todo:
                print(
                    f"ERROR: entry {entry.get('id')!r} has null status without "
                    f"classification_todo",
                    file=sys.stderr,
                )
                return 1
            status_cell = "(unset)"
        elif status not in ALLOWED:
            print(
                f"ERROR: entry {entry.get('id')!r} has invalid status {status!r}; "
                f"allowed: {sorted(ALLOWED)}",
                file=sys.stderr,
            )
            return 1
        else:
            status_cell = status
        notes = (entry.get("notes") or "").replace("|", "\\|").replace("\n", " ")
        lines.append(
            "| {id} | {command} | {status} | {notes} | {todo} |".format(
                id=entry.get("id", ""),
                command=entry.get("command", ""),
                status=status_cell,
                notes=notes,
                todo=todo,
            )
        )

    lines.append("")
    MD_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {MD_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
